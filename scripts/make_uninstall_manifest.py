"""Generate literal NSIS payload/removal instructions from a clean Windows dist.

No runtime manifest is trusted. The generated instructions are compiled into the
installer and delete only packaged paths, never recursively remove directories.
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path
import stat

ROOT = Path(__file__).resolve().parent.parent
PRIVATE_PARTS = {".local", ".git", ".env", "profiles", "accounts"}
RESERVED = {"CON", "PRN", "AUX", "NUL", *[f"COM{i}" for i in range(1, 10)],
            *[f"LPT{i}" for i in range(1, 10)]}


def nsis_literal(value: str) -> str:
    """Escape a quoted NSIS string, rejecting preprocessor/control injection."""
    if any(ord(char) < 32 for char in value) or "${" in value:
        raise ValueError(f"Unsupported control/preprocessor syntax in path: {value!r}")
    return value.replace("$", "$$").replace('"', '$\\"')


def _check_part(part: str) -> None:
    if (part in {".", ".."} or any(char in part for char in '<>:"/\\|?*')
            or part.endswith((".", " ")) or part.split(".", 1)[0].upper() in RESERVED):
        raise ValueError(f"Not a literal Windows filename: {part!r}")
    if part.casefold() in PRIVATE_PARTS or part.casefold().startswith(".env."):
        raise ValueError(f"Private state must never be packaged: {part}")
    nsis_literal(part)


def collect_payload(dist: Path) -> tuple[list[str], list[str]]:
    dist = Path(os.path.abspath(dist))
    if (not dist.is_dir() or dist.is_symlink()
            or getattr(dist.lstat(), "st_file_attributes", 0) & stat.FILE_ATTRIBUTE_REPARSE_POINT):
        raise ValueError("Payload must be an existing real directory.")
    files: list[str] = []
    directories: list[str] = []
    seen: set[str] = set()
    for folder, dirs, names in os.walk(dist, followlinks=False):
        for name in sorted(dirs + names):
            path = Path(folder) / name
            relative = path.relative_to(dist)
            for part in relative.parts:
                _check_part(part)
            if (relative.parts[0] not in {"SparkAssistant.exe", "SparkWorker.exe", "_internal"}
                    or (len(relative.parts) > 1 and relative.parts[0] != "_internal")):
                raise ValueError(f"Unexpected top-level payload: {relative}")
            info = path.lstat()
            if path.is_symlink() or getattr(info, "st_file_attributes", 0) & stat.FILE_ATTRIBUTE_REPARSE_POINT:
                raise ValueError(f"Linked payload entries are not allowed: {relative}")
            item = "\\".join(relative.parts)
            if item.casefold() in seen:
                raise ValueError(f"Case-insensitive payload collision: {relative}")
            seen.add(item.casefold())
            if path.is_dir():
                directories.append(item)
            elif path.is_file():
                files.append(item)
            else:
                raise ValueError(f"Not a regular payload entry: {relative}")
    if not {"SparkAssistant.exe", "SparkWorker.exe"}.issubset(files):
        raise ValueError("Payload is missing the desktop or worker executable.")
    return sorted(files), sorted(directories)


def render_manifest(dist: Path) -> str:
    dist = Path(os.path.abspath(dist))
    files, directories = collect_payload(dist)
    lines = ["; Generated by scripts/make_uninstall_manifest.py. Do not edit.",
             "; Paths are compile-time literals; unknown files are retained.",
             '!ifndef SPARK_GENERATED_UNINSTALL_MANIFEST',
             '!define SPARK_GENERATED_UNINSTALL_MANIFEST',
             '!macro SparkManifestFunctions',
             'Function SparkValidatePackagedPaths', '  Push $0',
             '  StrCpy $SparkDirectoryError ""']
    # Validate every file as well as directories: a file itself can be a link.
    for relative in directories + files:
        target = f'$INSTDIR\\{nsis_literal(relative)}'
        lines += [f'  Push "{target}"', '  Call SparkPathHasReparsePoint', '  Pop $0',
                  '  StrCmp $0 0 +3',
                  '  StrCpy $SparkDirectoryError "安装目标中的文件或目录含链接，已停止。"',
                  '  Goto spark_payload_checked']
    lines += ['spark_payload_checked:', '  Pop $0', 'FunctionEnd',
              'Function un.SparkRemovePackagedFiles', '  Push $0']
    for relative in files:
        target = f'$INSTDIR\\{nsis_literal(relative)}'
        lines += [f'  Push "{target}"', '  Call un.SparkPathHasReparsePoint', '  Pop $0',
                  '  StrCmp $0 0 0 +2', f'  Delete "{target}"']
    for relative in sorted(directories, key=lambda item: (item.count('\\'), item), reverse=True):
        target = f'$INSTDIR\\{nsis_literal(relative)}'
        lines += [f'  Push "{target}"', '  Call un.SparkPathHasReparsePoint', '  Pop $0',
                  '  StrCmp $0 0 0 +2', f'  RMDir "{target}"']
    lines += ['  Pop $0', 'FunctionEnd', '!macroend', '!macro SparkInstallPackagedFiles']
    for relative in files:
        parts = relative.split('\\')
        parent = '\\'.join(parts[:-1])
        output = '$INSTDIR' + ('\\' + nsis_literal(parent) if parent else '')
        source = str(dist.joinpath(*parts))
        nsis_literal(source)  # Validate controls/preprocessor syntax.
        if '"' in source:
            raise ValueError('Source directory is not a valid Windows path.')
        # File's source is evaluated at compile time (no $ variable expansion),
        # whereas /oname is a runtime target and must escape literal dollars.
        filename = nsis_literal(parts[-1])
        lines += [f'  SetOutPath "{output}"', f'  File "/oname={filename}" "{source}"']
    lines += ['  SetOutPath "$INSTDIR"', '!macroend', '!endif', '']
    return '\n'.join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dist', type=Path, default=ROOT / 'dist/SparkAssistant')
    parser.add_argument('--output', type=Path, default=ROOT / 'build/windows-uninstall-manifest.nsh')
    args = parser.parse_args()
    contents = render_manifest(args.dist)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(contents, encoding='utf-8')
    print(args.output)


if __name__ == '__main__':
    main()
